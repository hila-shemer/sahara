/* -------------------------------------------------- UDP flow table */

/* Craft a minimal UDP frame 10.0.2.15:sport -> dst:dport with payload
 * (checksum 0 -- accepted without verification). */
static uint16_t udp_frame(uint8_t *f, uint16_t sport, uint32_t dst,
                          uint16_t dport, const char *pay)
{
    uint16_t plen = (uint16_t)strlen(pay);
    uint16_t total = (uint16_t)(20u + 8u + plen);
    memset(f, 0, SE_NIC_FRAME_MIN);
    memcpy(f, peer_mac, 6u);
    memcpy(f + 6u, tv8 + 6u, 6u); /* guest MAC (unchecked anyway) */
    f[12] = 0x08;
    f[13] = 0x00;
    f[14] = 0x45;
    f[16] = (uint8_t)(total >> 8);
    f[17] = (uint8_t)total;
    f[22] = 64u; /* guest TTL, not propagated */
    f[23] = 17u;
    f[26] = 0x0A;
    f[28] = 0x02;
    f[29] = 0x0F;
    f[30] = (uint8_t)(dst >> 24);
    f[31] = (uint8_t)(dst >> 16);
    f[32] = (uint8_t)(dst >> 8);
    f[33] = (uint8_t)dst;
    fix_ip_csum(f);
    f[34] = (uint8_t)(sport >> 8);
    f[35] = (uint8_t)sport;
    f[36] = (uint8_t)(dport >> 8);
    f[37] = (uint8_t)dport;
    f[38] = 0;
    f[39] = (uint8_t)(8u + plen);
    memcpy(f + 42u, pay, plen);
    uint16_t flen = (uint16_t)(14u + total);
    return flen < SE_NIC_FRAME_MIN ? SE_NIC_FRAME_MIN : flen;
}

static void test_udp_flows(void)
{
    SeNic n;
    nic_start(&n);
    uint8_t f[SE_NIC_FRAME_MAX];

    /* First datagram creates flow 0 and forwards the payload. */
    uint16_t len = udp_frame(f, 5000u, 0x5DB8D822u, 9999u, "hello");
    SeNic_tx(&n, f, len);
    RWC_ASSERT(cap.nframes == 0u && cap.nsends == 1u);
    RWC_ASSERT(cap.sflow[0] == 0u && !cap.sdns[0]);
    RWC_ASSERT(cap.sip[0] == 0x5DB8D822u && cap.sport[0] == 9999u);
    RWC_ASSERT(cap.slen[0] == 5u && memcmp(cap.sdata[0], "hello", 5u) == 0);
    cap_clear();
    /* Same key: reuses flow 0. Different port: flow 1. */
    len = udp_frame(f, 5000u, 0x5DB8D822u, 9999u, "again");
    SeNic_tx(&n, f, len);
    RWC_ASSERT(cap.nsends == 1u && cap.sflow[0] == 0u);
    cap_clear();
    len = udp_frame(f, 5000u, 0x5DB8D822u, 9998u, "other");
    SeNic_tx(&n, f, len);
    RWC_ASSERT(cap.nsends == 1u && cap.sflow[0] == 1u);
    cap_clear();
    /* DNS to 10.0.2.3:53: a flagged flow on the same table (6.6). */
    len = udp_frame(f, 5001u, 0x0A000203u, 53u, "dnsq");
    SeNic_tx(&n, f, len);
    RWC_ASSERT(cap.nsends == 1u && cap.sflow[0] == 2u && cap.sdns[0]);
    RWC_ASSERT(cap.sip[0] == 0x0A000203u && cap.sport[0] == 53u);
    cap_clear();
    /* In-subnet non-services and the limited broadcast: drop (6.2). */
    len = udp_frame(f, 5002u, 0x0A000209u, 99u, "x");
    SeNic_tx(&n, f, len);
    len = udp_frame(f, 5002u, 0xFFFFFFFFu, 99u, "x");
    SeNic_tx(&n, f, len);
    len = udp_frame(f, 5002u, 0x0A000202u, 68u, "x");
    SeNic_tx(&n, f, len);
    expect_silence();

    /* Inbound datagram on flow 0: the 6.5 synthesized frame, padded
     * to 60, guest-visible remote restored. */
    SeNic_datagram(&n, 0u, (const uint8_t *)"world", 5u);
    RWC_ASSERT(cap.nframes == 1u && cap.flen[0] == 60u);
    const uint8_t *r = cap.frame[0];
    RWC_ASSERT(memcmp(r, tv8 + 6u, 6u) == 0); /* dst = guest MAC */
    RWC_ASSERT(rd32(r + 26u) == 0x5DB8D822u);
    RWC_ASSERT(rd32(r + 30u) == 0x0A00020Fu);
    RWC_ASSERT(rd16(r + 34u) == 9999u && rd16(r + 36u) == 5000u);
    RWC_ASSERT(rd16(r + 38u) == 13u); /* UDP length 8 + 5 */
    RWC_ASSERT(memcmp(r + 42u, "world", 5u) == 0);
    for (unsigned i = 47u; i < 60u; i++)
        RWC_ASSERT(r[i] == 0u); /* zero padding to the minimum */
    check_reply_constants(r, 60u);
    cap_clear();

    /* Max-size inbound fills the frame exactly; one byte more drops. */
    static uint8_t big[1473];
    memset(big, 0x5A, sizeof big);
    SeNic_datagram(&n, 0u, big, 1472u);
    RWC_ASSERT(cap.nframes == 1u && cap.flen[0] == SE_NIC_FRAME_MAX);
    RWC_ASSERT(cap.frame[0][1513] == 0x5Au);
    check_reply_constants(cap.frame[0], SE_NIC_FRAME_MAX);
    cap_clear();
    SeNic_datagram(&n, 0u, big, 1473u);
    expect_silence();

    /* The 64-flow limit: fill the table, then the 65th key's first
     * datagram is dropped and creates nothing (6.5). */
    for (uint16_t i = 3u; i < 64u; i++) {
        len = udp_frame(f, (uint16_t)(6000u + i), 0x08080808u,
                        (uint16_t)(1000u + i), "fill");
        SeNic_tx(&n, f, len);
        RWC_ASSERT(cap.nsends == 1u && cap.sflow[0] == i);
        cap_clear();
    }
    RWC_ASSERT(n.flow_count == 64u);
    len = udp_frame(f, 7777u, 0x08080808u, 7777u, "over");
    SeNic_tx(&n, f, len);
    expect_silence();
    RWC_ASSERT(n.flow_count == 64u);
    /* Existing flows still forward. */
    len = udp_frame(f, 5000u, 0x5DB8D822u, 9999u, "still");
    SeNic_tx(&n, f, len);
    RWC_ASSERT(cap.nsends == 1u && cap.sflow[0] == 0u);
    cap_clear();
}

