# t_nic.s — the scripted NIC session guest (run-gui-tests, --nic
# fake): the TV-S1 DHCP handshake (TV-3 -> TV-4, TV-5 -> TV-6), an ARP
# probe for the gateway (TV-1 -> TV-2), a virtual-host ping (TV-8 ->
# TV-9) — all locally synthesized replies — then one UDP flow to
# 1.2.3.4:9999 whose payload the fake backend echoes back at the next
# pump tick, exposed as the expected 6.5 inbound frame. Every reply is
# compared byte-for-byte against its embedded expectation, RX_LEN
# included; HALT 600d on success. Per nic.md 7.1 rule 5 the guest
# never assumes the +1 stamp: it WFIs (IE stays 0 — the wake needs
# only the level-pending condition) and re-reads RX_LEN.

        .equ DEV_NIC_BASE, 0x0F030000
        .equ NIC_TXBUF, 0x0F040000
        .equ NIC_RXBUF, 0x0F050000
        .equ PASS_MAGIC, 0x600D

        .org 0x1000
start:
        li r17, DEV_NIC_BASE
        ldz.64 r16, [r17 + 16] # TV-S1 step 1: RX_LEN reads 0
        cmpeq p3, r16, 0
        (!p3) b fail

        la.abs r1, tv3         # DHCP DISCOVER -> byte-exact OFFER
        li r2, 342
        jal send
        li r2, 342
        jal waitlen
        la.abs r1, tv4
        li r2, 342
        jal check
        st.64 [r17 + 24], zero # RX_POP

        la.abs r1, tv5         # DHCP REQUEST -> byte-exact ACK
        li r2, 342
        jal send
        li r2, 342
        jal waitlen
        la.abs r1, tv6
        li r2, 342
        jal check
        st.64 [r17 + 24], zero

        la.abs r1, tv1         # ARP who-has 10.0.2.2 -> TV-2 reply
        li r2, 60
        jal send
        li r2, 60
        jal waitlen
        la.abs r1, tv2
        li r2, 60
        jal check
        st.64 [r17 + 24], zero

        la.abs r1, tv8         # ping the gateway -> TV-9 echo reply
        li r2, 60
        jal send
        li r2, 60
        jal waitlen
        la.abs r1, tv9
        li r2, 60
        jal check
        st.64 [r17 + 24], zero

        la.abs r1, udptx       # one UDP datagram out through the flow
        li r2, 60              # table; the fake backend echoes it at
        jal send               # the next pump tick
        li r2, 60
        jal waitlen
        la.abs r1, udprx
        li r2, 60
        jal check
        st.64 [r17 + 24], zero

        ldz.64 r16, [r17 + 16] # mailbox drained at session end
        cmpeq p3, r16, 0
        (!p3) b fail
        li r0, PASS_MAGIC
        halt
fail:
        li r0, 0xBAD
        halt

        # send: copy r2 bytes from [r1] to the TX buffer, then ring
        # the doorbell with r2. Clobbers r1, r3, r4, r5.
send:
        li r3, NIC_TXBUF
        mov r4, r2
s1:
        ldz.8 r5, [r1]
        st.8 [r3], r5
        add r1, r1, 1
        add r3, r3, 1
        sub r4, r4, 1
        cmpeq p3, r4, 0
        (!p3) b s1
        st.64 [r17], r2        # TX_DOORBELL
        ret

        # waitlen: sleep until RX_LEN != 0, then require it == r2.
        # WFI wakes on the level-pending NIC condition without IE.
waitlen:
w1:
        ldz.64 r16, [r17 + 16]
        cmpeq p3, r16, 0
        (!p3) b w2
        wfi
        b w1
w2:
        cmpeq p3, r16, r2
        (!p3) b fail
        ret

        # check: compare RX buffer bytes [0, r2) against [r1].
        # Clobbers r1, r2, r3, r5, r6.
check:
        li r3, NIC_RXBUF
c1:
        ldz.8 r5, [r1]
        ldz.8 r6, [r3]
        cmpeq p3, r5, r6
        (!p3) b fail
        add r1, r1, 1
        add r3, r3, 1
        sub r2, r2, 1
        cmpeq p3, r2, 0
        (!p3) b c1
        ret

