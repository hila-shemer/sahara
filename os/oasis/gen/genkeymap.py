#!/usr/bin/env python3
"""Emit build/keymap.s: two 256-byte HID->ASCII tables (plain, shifted).

Source of truth for the kernel's keyboard translation AND for the test
feed builder (mkfeed.py imports this module to reverse-map characters to
key events) - one table, two consumers, no drift.

The HID usage set is the closed 103-ID table of devspec/input.md 2.2;
the self-test below asserts we map only IDs inside it and that every
value is one the console understands (0 = drop, 0x08 backspace, 0x0A
newline, printables 0x20-0x7E). Modifiers 0xE0-0xE7 map to 0 here - the
kernel tracks shift itself from their press/release events (input.md
2.3: modifiers are ordinary keys, translation is guest policy).
"""

import sys

# The closed usage-ID set of input.md 2.2 (103 IDs).
ALLOWED_IDS = frozenset(
    list(range(0x04, 0x1E))      # letters
    + list(range(0x1E, 0x28))    # digits
    + list(range(0x28, 0x32))    # enter..right-bracket, backslash
    + list(range(0x33, 0x3A))    # ; ' ` , . / capslock
    + list(range(0x3A, 0x46))    # F1-F12
    + list(range(0x46, 0x53))    # nav/system
    + list(range(0x53, 0x64))    # keypad
    + list(range(0xE0, 0xE8))    # modifiers
)
assert len(ALLOWED_IDS) == 103

HID_LSHIFT, HID_RSHIFT = 0xE1, 0xE5

BS, NL = 0x08, 0x0A


def _build():
    plain = [0] * 256
    shift = [0] * 256
    for i in range(26):                      # 0x04.. letters
        plain[0x04 + i] = ord('a') + i
        shift[0x04 + i] = ord('A') + i
    digits = "1234567890"
    shifted_digits = "!@#$%^&*()"
    for i in range(10):                      # 0x1E.. main-row digits
        plain[0x1E + i] = ord(digits[i])
        shift[0x1E + i] = ord(shifted_digits[i])
    both = {0x28: NL, 0x2A: BS, 0x2C: ord(' ')}
    for hid, v in both.items():
        plain[hid] = shift[hid] = v
    pairs = {0x2D: "-_", 0x2E: "=+", 0x2F: "[{", 0x30: "]}",
             0x31: "\\|", 0x33: ";:", 0x34: "'\"", 0x35: "`~",
             0x36: ",<", 0x37: ".>", 0x38: "/?"}
    for hid, (p, s) in pairs.items():
        plain[hid] = ord(p)
        shift[hid] = ord(s)
    # Keypad: shift-invariant. (No NumLock state in M1 - always digits.)
    kp = {0x54: '/', 0x55: '*', 0x56: '-', 0x57: '+'}
    for hid, ch in kp.items():
        plain[hid] = shift[hid] = ord(ch)
    plain[0x58] = shift[0x58] = NL           # keypad enter
    for i in range(9):                       # 0x59.. keypad 1-9
        plain[0x59 + i] = shift[0x59 + i] = ord('1') + i
    plain[0x62] = shift[0x62] = ord('0')
    plain[0x63] = shift[0x63] = ord('.')
    return plain, shift


PLAIN, SHIFT = _build()


def _selftest():
    for tab in (PLAIN, SHIFT):
        assert len(tab) == 256
        for hid, v in enumerate(tab):
            if v:
                assert hid in ALLOWED_IDS, f"mapped ID 0x{hid:02x} not in input.md 2.2"
                assert v in (BS, NL) or 0x20 <= v <= 0x7E, \
                    f"ID 0x{hid:02x} maps to non-console byte 0x{v:02x}"
    for hid in range(0xE0, 0xE8):            # modifiers never translate
        assert PLAIN[hid] == 0 and SHIFT[hid] == 0
    # Every printable the shell needs is reachable.
    reach = set(PLAIN) | set(SHIFT)
    for ch in range(0x20, 0x7F):
        assert ch in reach, f"unreachable ASCII 0x{ch:02x}"


_selftest()


def char_to_key(ch):
    """Reverse map for mkfeed: char -> (hid, needs_shift). Prefers the
    main-row key (lowest ID) when several produce the same char."""
    c = ord(ch) if isinstance(ch, str) else ch
    for hid in sorted(ALLOWED_IDS):
        if PLAIN[hid] == c:
            return hid, False
    for hid in sorted(ALLOWED_IDS):
        if SHIFT[hid] == c:
            return hid, True
    raise KeyError(f"no key produces 0x{c:02x}")


def emit(path):
    lines = ["# keymap.s - GENERATED by gen/genkeymap.py - DO NOT EDIT.",
             "# HID usage ID -> ASCII, US layout; 0 = no translation.",
             "        .align 16"]
    for label, tab in (("keymap_plain", PLAIN), ("keymap_shift", SHIFT)):
        lines.append(f"{label}:")
        for i in range(0, 256, 16):
            row = ", ".join(f"0x{v:02x}" for v in tab[i:i + 16])
            lines.append(f"        .byte {row}")
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(f"usage: {sys.argv[0]} OUT.s")
    emit(sys.argv[1])
