def glyph_rows(ch):
    """16 row-bytes for ch; bit 7 = leftmost pixel."""
    art = ART[ch]
    assert len(art) <= BAND_ROWS, f"{ch!r}: {len(art)} band rows"
    rows = [0] * 16
    for i, line in enumerate(art):
        assert len(line) <= 8, f"{ch!r} row {i} too wide"
        b = 0
        for j, px in enumerate(line):
            assert px in ".#", f"{ch!r} row {i}: bad char {px!r}"
            if px == '#':
                b |= 0x80 >> j
        rows[BAND_TOP + i] = b
    return rows


FONT = {ch: glyph_rows(ch) for ch in ART}
FONT_BYTES = {ch: bytes(rows) for ch, rows in FONT.items()}


def _selftest():
    assert sorted(map(ord, ART)) == list(range(0x20, 0x7F)), \
        "font must cover exactly ASCII 0x20-0x7E"
    seen = {}
    for ch, b in FONT_BYTES.items():
        assert len(b) == 16
        if ch != ' ':
            assert any(b), f"{ch!r} is blank - collides with space"
            assert b not in seen, f"{ch!r} and {seen[b]!r} share a bitmap"
            seen[b] = ch
        # column 7 blank (inter-glyph spacing; 2 st128 per row rely on
        # the cell being self-contained either way, this is cosmetic)
        assert all((row & 1) == 0 for row in b), f"{ch!r} uses column 7"


_selftest()


def emit(path):
    lines = ["# font.s - GENERATED by gen/genfont.py - DO NOT EDIT.",
             "# 8x16, ASCII 0x20-0x7E, 16 rows per glyph, bit 7 = leftmost.",
             "        .align 16",
             "font8x16:"]
    for code in range(0x20, 0x7F):
        ch = chr(code)
        name = ch if ch != '#' else "'#'"
        lines.append(f"        # 0x{code:02x} {name}")
        for row in FONT[ch]:
            lines.append(f"        .byte 0x{row:02x}")
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(f"usage: {sys.argv[0]} OUT.s")
    emit(sys.argv[1])
